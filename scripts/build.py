#!/usr/bin/env python3
"""Generate the derived Elasticsearch files from their sources.

Usage: scripts/build.py [--check]

Writes:
  elasticsearch/ingest_pipeline/logs-kea.dhcp.json   pipeline JSON, from the YAML source
  elasticsearch/dev_tools/install-fleet.txt          Kibana Dev Tools console requests

--check exits non-zero when a committed file is out of date (scripts/test.sh runs it).
"""
import json
import pathlib
import sys

import yaml

ROOT = pathlib.Path(__file__).resolve().parent.parent
PIPELINE_SRC = ROOT / "elasticsearch/ingest_pipeline/logs-kea.dhcp.yml"
PIPELINE_JSON = PIPELINE_SRC.with_suffix(".json")
MAPPINGS = ROOT / "elasticsearch/index_template/logs-kea.dhcp@package.json"
CONSOLE = ROOT / "elasticsearch/dev_tools/install-fleet.txt"

SAMPLE = (
    "2026-10-27 08:01:13.601 INFO  [kea-dhcp4.leases/1873.140226107447040] DHCP4_LEASE_ALLOC "
    "[hwtype=1 08:00:2b:02:3f:4e], cid=[01:08:00:2b:02:3f:4e], tid=0x3d18f5e4: "
    "lease 192.0.2.10 has been allocated for 4000 seconds"
)

CONSOLE_HEADER = """\
# Kea DHCP: manual install for Fleet's Custom Logs integration
#
# Paste this whole file into Kibana > Dev Tools > Console, select everything
# (Ctrl+A) and press Ctrl+Enter to send every request. Each one should
# return "acknowledged": true. See docs/manual-install.md for the full steps.
#
# Generated by scripts/build.py from the files in elasticsearch/. Do not edit.

"""


def console(pipeline, mappings):
    parts = [
        CONSOLE_HEADER,
        "# 1. Ingest pipeline that parses Kea log lines.\n",
        "PUT _ingest/pipeline/logs-kea.dhcp\n",
        json.dumps(pipeline, indent=2),
        "\n\n",
        "# 2. Field mappings. Fleet's logs-kea.dhcp index template includes the\n"
        "#    logs-kea.dhcp@custom component template, so the mappings go there.\n"
        "#    This replaces any existing logs-kea.dhcp@custom component template.\n",
        "PUT _component_template/logs-kea.dhcp@custom\n",
        json.dumps(mappings, indent=2),
        "\n\n",
        "# 3. Check: parse a sample line. The response should show\n"
        '#    "event.action": "lease-allocated" and "client.ip": "192.0.2.10".\n',
        "POST _ingest/pipeline/logs-kea.dhcp/_simulate\n",
        json.dumps({"docs": [{"_source": {"message": SAMPLE}}]}, indent=2),
        "\n",
    ]
    return "".join(parts)


def main():
    pipeline = yaml.safe_load(PIPELINE_SRC.read_text())
    mappings = json.loads(MAPPINGS.read_text())
    outputs = {
        PIPELINE_JSON: json.dumps(pipeline, indent=2) + "\n",
        CONSOLE: console(pipeline, mappings),
    }
    check = "--check" in sys.argv
    stale = []
    for path, rendered in outputs.items():
        if check:
            if not path.exists() or path.read_text() != rendered:
                stale.append(str(path.relative_to(ROOT)))
            continue
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(rendered)
        print(f"wrote {path.relative_to(ROOT)}")
    if stale:
        sys.exit(f"stale: {', '.join(stale)}; run scripts/build.py")


if __name__ == "__main__":
    main()
